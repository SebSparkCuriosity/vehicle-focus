const DAY = 86_400_000;

/** ISO datetime offset from now by `days`, optionally pinned to an hour of the day. */
export function at(days: number, hour?: number, minute = 0): string {
  const d = new Date(Date.now() + days * DAY);
  if (hour !== undefined) d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

/** ISO date (yyyy-mm-dd) offset from now by `days`. */
export function on(days: number): string {
  return at(days, 12).slice(0, 10);
}

function monthsAgo(m: number): string {
  return on(-Math.round(m * 30.4));
}

